"""Write the resolved external dependency inventory (ADR-0033).

Reads `cargo metadata --locked` and prints one tab-separated row per external
package: name, version, source, licence, whether it has a build script, and
the reach classes through which the workspace pulls it in:

- runtime: normal dependency edges with no target condition, or target
  conditions other than cfg(loom);
- build: reached through a build-dependency edge or inside a proc macro;
- dev: reached only through dev-dependency edges;
- loom: reached only through the cfg(loom) target dependency.

`make deps-inventory` regenerates quantstratum-docs: karyos/dependency-inventory.tsv and CI fails
when the committed file differs from the lockfile.
"""

import json
import subprocess
import sys


def main() -> int:
    raw = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    meta = json.loads(raw)
    packages = {p["id"]: p for p in meta["packages"]}
    workspace = set(meta["workspace_members"])
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}

    # Breadth-first walk from the workspace, carrying the reach class.
    reach = {}
    conditions = {}
    queue = []
    for member in workspace:
        for dep in nodes[member]["deps"]:
            for kind in dep["dep_kinds"]:
                queue.append((dep["pkg"], classify(kind)))
                note_condition(conditions, dep["pkg"], kind)
    while queue:
        pkg, cls = queue.pop()
        if pkg in workspace:
            continue
        is_proc_macro = any(
            "proc-macro" in t["kind"] for t in packages[pkg]["targets"]
        )
        if is_proc_macro and cls == "runtime":
            cls = "build"
        classes = reach.setdefault(pkg, set())
        if cls in classes:
            continue
        classes.add(cls)
        for dep in nodes[pkg]["deps"]:
            for kind in dep["dep_kinds"]:
                child = cls
                if kind["kind"] == "build" or is_proc_macro:
                    child = "build" if cls == "runtime" else cls
                if kind["kind"] == "dev":
                    continue
                note_condition(conditions, dep["pkg"], kind)
                queue.append((dep["pkg"], child))

    out = sys.stdout
    out.write("# Generated by scripts/dependency-inventory.py; do not edit.\n")
    out.write("name\tversion\tsource\tlicense\tbuild_script\treach\ttarget_conditions\n")
    rows = []
    for pkg_id, classes in reach.items():
        p = packages[pkg_id]
        has_build = any("custom-build" in t["kind"] for t in p["targets"])
        source = "crates.io" if "crates.io" in (p.get("source") or "") else p.get("source")
        rows.append(
            (
                p["name"],
                p["version"],
                source,
                p.get("license") or "",
                "yes" if has_build else "no",
                ",".join(sorted(classes)),
                target_conditions(conditions.get(pkg_id)),
            )
        )
    for row in sorted(rows):
        out.write("\t".join(row) + "\n")
    return 0


def note_condition(conditions: dict, pkg: str, kind: dict) -> None:
    """Record the target condition of one incoming edge (None if unconditional)."""
    target = kind.get("target")
    if target and "loom" in target:
        target = None
    conditions.setdefault(pkg, set()).add(target)


def target_conditions(edges) -> str:
    """'always' if any incoming edge is unconditional, else the conditions."""
    if not edges or None in edges:
        return "always"
    return " | ".join(sorted(edges))


def classify(kind: dict) -> str:
    target = kind.get("target") or ""
    if "loom" in target:
        return "loom"
    if kind["kind"] == "dev":
        return "dev"
    if kind["kind"] == "build":
        return "build"
    return "runtime"


if __name__ == "__main__":
    sys.exit(main())
