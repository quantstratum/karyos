"""Independent vectors of the encrypted protection profile v1 (ADR-0114).

Gate H5, second implementation: every value is computed here from the
frozen encoding of ADR-0114 sections 2, 4 and 5 with the Python
`cryptography` package (HKDF-SHA-256, AESGCMSIV) and the standard `hmac`
module, never from the Rust implementation. Run:

    python3 -I enc_vectors.py

It prints the RFC 8452 C.2 check, the KDF `info` and key of every domain,
the pairwise trailer key, and the sealed datagrams, as hex.
"""
import hashlib
import hmac
import struct

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCMSIV
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

LABEL = b"karyos-wire-enc-v01\0"
PROFILE_ID = 16
DOMAIN = {"snd": 1, "rcv": 4, "setup": 5, "rsp": 6}

IKM = bytes(range(32))
PAIRWISE_SECRET = bytes(0xA0 + i for i in range(32))
KEY_EPOCH = 5
PAIRWISE_EPOCH = 9
SESSION_ID = -2
STREAM_ID = 1001


def w128(w0, w1):
    return struct.pack("<QQ", w0, w1)


IB = w128(0x0102030405060708, 0x1112131415161718) + struct.pack("<QQ", 7, 3)
BOOT = w128(0x2122232425262728, 0x3132333435363738)
RECEIVER_ID = 42
RB = BOOT + struct.pack("<Q", RECEIVER_ID)
CHALLENGE_SALT = BOOT + w128(0x4142434445464748, 0x5152535455565758)


def purpose(tag):
    return tag.encode().ljust(8, b"\0")


def info(domain, party_epoch):
    head = LABEL + purpose(domain) + struct.pack("<IH", KEY_EPOCH, party_epoch)
    if domain == "snd":
        body = IB
    elif domain in ("rcv", "rsp"):
        body = RB + IB
    else:
        body = IB
    return head + body + bytes([PROFILE_ID])


def hkdf(ikm, salt, info_bytes):
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=salt or None, info=info_bytes).derive(ikm)


def pairwise_info(epoch):
    return LABEL + purpose("pauth") + struct.pack("<I", epoch) + RB + IB + bytes([PROFILE_ID])


def header(domain, party_epoch, seq, total):
    party = IB if domain in ("snd", "setup") else RB + bytes(8)
    return (
        struct.pack("<iBBHBBBB", total, 1, 0, 0x21, PROFILE_ID, 16, DOMAIN[domain], 0)
        + struct.pack("<IHH", KEY_EPOCH, party_epoch, 0)
        + struct.pack("<iiQ", SESSION_ID, STREAM_ID, seq)
        + party
    )


def seal(domain, party_epoch, salted, seq, frames):
    key = hkdf(IKM, CHALLENGE_SALT if salted else b"", info(domain, party_epoch))
    receiver = domain in ("rcv", "rsp")
    plain_len = len(frames) + (20 if receiver else 0)
    total = 68 + plain_len + 16
    head = header(domain, party_epoch, seq, total)
    plaintext = frames
    if receiver:
        kp = hkdf(PAIRWISE_SECRET, b"", pairwise_info(PAIRWISE_EPOCH))
        partial = frames + struct.pack("<I", PAIRWISE_EPOCH)
        tag = hmac.new(kp, LABEL + head + partial, hashlib.sha256).digest()[:16]
        plaintext = partial + tag
    nonce = bytes([DOMAIN[domain], 0, 0, 0]) + struct.pack("<Q", seq)
    return head + AESGCMSIV(key).encrypt(nonce, plaintext, LABEL + head)


def frames(length, mul, add):
    return bytes((i * mul + add) % 256 for i in range(length))


# RFC 8452 Appendix C.2, the first vector (empty plaintext, empty AAD).
RFC = AESGCMSIV(bytes.fromhex("01" + "00" * 31)).encrypt(
    bytes.fromhex("030000000000000000000000"), b"", b""
)
assert RFC.hex() == "07f5f4169bbf55a8400cd47ea6fd400f", RFC.hex()
print("# SPDX-License-Identifier: Apache-2.0")
print("# Generated by enc_vectors.py; do not edit (gate H5, ADR-0114).")
print("rfc8452 c.2 #1 ok")

for name, domain, party_epoch, salted in [
    ("snd unicast", "snd", 2, True),
    ("snd multicast", "snd", 2, False),
    ("snd next epoch", "snd", 3, True),
    ("rcv unicast", "rcv", 2, True),
    ("rcv multicast", "rcv", 2, False),
    ("setup", "setup", 0, False),
    ("rsp", "rsp", 0, False),
]:
    i = info(domain, party_epoch)
    print(f"kdf {name}: info {i.hex()} key {hkdf(IKM, CHALLENGE_SALT if salted else b'', i).hex()}")
print(f"pairwise: info {pairwise_info(PAIRWISE_EPOCH).hex()} key {hkdf(PAIRWISE_SECRET, b'', pairwise_info(PAIRWISE_EPOCH)).hex()}")

for name, domain, party_epoch, salted, seq, body in [
    ("snd", "snd", 2, True, 0x0102, frames(40, 7, 3)),
    ("snd empty", "snd", 2, False, 0, b""),
    ("rsp", "rsp", 0, False, 3, frames(56, 13, 1)),
    ("rcv", "rcv", 2, True, 77, frames(32, 5, 9)),
    ("setup", "setup", 0, False, 0, frames(72, 11, 0)),
]:
    print(f"envelope {name}: {seal(domain, party_epoch, salted, seq, body).hex()}")
